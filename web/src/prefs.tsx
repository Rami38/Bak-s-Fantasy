type Copy = { [K in keyof (typeof copy)["en"]]: string };

type Prefs = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  theme: Theme;
  setTheme: (theme: Theme) => void;
  timeZone: string;
  t: Copy;
};

const Ctx = createContext<Prefs | null>(null);

export function PrefsProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem("baks-lang") === "fr" ? "fr" : "en"));
  const [theme, setTheme] = useState<Theme>(() => (localStorage.getItem("baks-theme") === "light" ? "light" : "dark"));
  const timeZone = Intl.DateTimeFormat().resolvedOptions().timeZone || "Europe/Paris";

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    document.documentElement.lang = lang;
    localStorage.setItem("baks-lang", lang);
    localStorage.setItem("baks-theme", theme);
  }, [lang, theme]);

  return <Ctx.Provider value={{ lang, setLang, theme, setTheme, timeZone, t: copy[lang] }}>{children}</Ctx.Provider>;
}

export function usePrefs(): Prefs {
  const value = useContext(Ctx);
  if (!value) throw new Error("Prefs are missing.");
  return value;
}
